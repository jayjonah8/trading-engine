#![allow(dead_code)]

use std::collections::{
    HashMap,
    HashSet,
};
use std::time::{
    Instant,
    SystemTime,
};


// ============================================================
// TRADE STATUS
// ============================================================

#[derive(Debug, Clone, Copy, PartialEq, Eq)]
pub enum TradeStatus {
    Open,
    Closing,
    Closed,
}


// ============================================================
// COMPLETED OPEN TRADE
// ============================================================

// The main distinction is: opened_ms = stored/serializable time, 
// entry_time = reliable elapsed-duration timer, 
// entry_wall_time = real-world clock time.

#[derive(Debug, Clone)]
pub struct Trade {
    /// Unique bot-level trade id.
    pub id: String,

    /// Trading symbol, e.g. "AAPL".
    pub symbol: String,

    /// True = long, false = short.
    pub is_long: bool,

    /// Signed quantity:
    /// +qty = long
    /// -qty = short
    pub qty: f64,

    /// FINAL average entry fill price from the exchange.
    pub executed_entry_avg_px: f64,

    /// FINAL average exit fill price from the exchange.
    /// None while the trade is still open.
    pub executed_exit_avg_px: Option<f64>,

    /// Strategy signal price when the opening trade intent was created.
    pub entry_signal_price: f64,

    /// Engine signal price when the closing trade was submitted.
    /// None while the trade is still open.
    pub exit_signal_price: Option<f64>,

    /// Exchange OPEN order ID.
    pub oid: String,

    /// Client OPEN order ID generated by engine.
    pub cid: String,

    /// Strategy that opened this trade.
    pub strategy: String,

    /// UTC timestamp in milliseconds when the entry fully completed.
    ///
    /// Represents the final opening fill time and is useful for logging,
    /// trade history, IDs, and other serializable time-based data.
    pub opened_ms: i64,

    /// Unrealized PnL.
    pub unrealized_pnl: f64,

    /// Current trade state.
    pub status: TradeStatus,

    /// Dollar amount requested for trade.
    pub trade_amount_usd: f64,

    /// Take-profit percentage.
    pub exit_profit_percent: f64,

    /// Stop-loss percentage.
    pub exit_loss_percent: f64,

    /// Emergency exit percentage.
    pub emergency_exit_percent: f64,

    /// Blocks normal stop-loss for a duration.
    pub min_sl_delay: u64,

    /// Enables time-based exit.
    pub enable_trade_duration: bool,

    /// Maximum trade duration.
    pub trade_duration_secs: Option<u64>,

    /// Monotonic timestamp captured when the entry fully completed.
    ///
    /// Used for elapsed-time logic such as minimum stop-loss delays and
    /// maximum trade duration. `Instant` is preferred for duration checks
    /// because it is unaffected by system clock changes.
    pub entry_time: Option<Instant>,

    /// Wall-clock timestamp captured when the entry fully completed.
    ///
    /// Represents the real-world entry time and can be used when logic needs
    /// an actual calendar/UTC time rather than only an elapsed duration.
    pub entry_wall_time: Option<SystemTime>,

    /// True when trade is simulated (backtest should = false).
    pub is_simulated: bool,

    /// Client ID for active close request.
    pub close_cid: Option<String>,

    /// Exchange CLOSE order ID.
    pub close_oid: Option<String>,
}


// ============================================================
// LIVE TRADES
// ============================================================

#[derive(Debug, Default, Clone)]
pub struct Trades {
    pub live: HashMap<String, Trade>,
}


impl Trades {
    pub fn upsert(
        &mut self,
        trade: Trade,
    ) {
        self.live.insert(
            trade.id.clone(),
            trade,
        );
    }


    pub fn close(
        &mut self,
        id: &str,
    ) {
        if let Some(trade) =
            self.live.get_mut(id)
        {
            trade.status =
                TradeStatus::Closed;
        }
    }


    // Counts every trade that still occupies one of the bot's live position slots.
    //
    // A trade with TradeStatus::Open is counted because the position is actively held.
    // A trade with TradeStatus::Closing is ALSO counted because the position still exists
    // at the exchange until the final close fill is confirmed.
    //
    // This is important for max_gross_positions gating. A close request being submitted
    // does not mean the position is gone yet, so its slot must not be reused early.
    //
    // Example:
    //   max_gross_positions = 8
    //
    //   7 Open
    //   1 Closing
    //   0 PendingOpen
    //
    //   booked_positions() = 8
    //
    // No new position should be allowed yet. Once the Closing trade receives its final
    // CloseFill and becomes Closed/removed, booked_positions() drops to 7 and a new
    // position is allowed to use the newly available slot.
    pub fn count_open(&self) -> usize {
        self.live
            .values()
            .filter(|trade| {
                trade.status == TradeStatus::Open
                    || trade.status == TradeStatus::Closing
            })
            .count()
    }


    pub fn remove(
        &mut self,
        id: &str,
    ) -> Option<Trade> {
        self.live.remove(id)
    }


    pub fn has_open_trade_for_symbol(
        &self,
        symbol: &str,
    ) -> bool {
        self.live
            .values()
            .any(
                |trade| {
                    trade.symbol == symbol
                        && (
                            trade.status == TradeStatus::Open
                            || trade.status == TradeStatus::Closing
                        )
                }
            )
    }
}


// ============================================================
// PENDING OPEN
// ============================================================

/// An entry order that has been created by the engine but has
/// not yet received its final fill from the exchange.
///
/// Created BEFORE the REST request is sent.
///
/// Removed only after:
///
///     ExecEvent::OpenFill
///
/// or a terminal failure.
#[derive(Debug, Clone)]
pub struct PendingOpen {
    /// Engine-generated client order ID used to track and correlate this opening order.
    pub cid: String,

    /// Exchange-generated order ID; None until the REST order request is acknowledged.
    pub oid: Option<String>,

    /// Symbol being opened on the exchange, e.g. "AAPL".
    pub symbol: String,

    /// Strategy that created and owns this opening order.
    pub strategy: String,

    /// True for a long position and false for a short position.
    pub is_long: bool,

    /// Estimated quantity calculated from trade_amount_usd / intent price.
    ///
    /// This is informational only because live Alpaca entries are submitted
    /// using dollar notional, not this quantity. The actual position quantity
    /// must come from Alpaca's filled_qty after the order executes.
    pub requested_qty: f64,

    /// Actual cumulative quantity Alpaca has filled so far.
    ///
    /// Updated from Alpaca order.filled_qty and becomes the authoritative
    /// position quantity once the opening order receives its final fill.
    pub filled_qty: f64,

    /// Actual cumulative average execution price of all fills received so far.
    ///
    /// Updated from Alpaca order.filled_avg_price and becomes the trade's
    /// authoritative entry price after the final opening fill.
    pub avg_fill_px: Option<f64>,

    /// Strategy signal price when the opening trade intent was created.
    pub signal_price: f64,

    /// Unique Alpaca execution IDs that have already been processed by the engine.
    ///
    /// Used to prevent the same partial or final execution from being applied
    /// more than once if an execution event is received again.
    pub execution_ids: HashSet<String>,

    /// Engine timestamp in milliseconds when the opening order was created.
    pub ts_ms: i64,

    /// Dollar amount requested by the strategy and submitted to Alpaca as notional.
    pub trade_amount_usd: f64,

    /// Profit percentage at which the completed trade should be exited.
    pub exit_profit_percent: f64,

    /// Loss percentage at which the completed trade should be exited.
    pub exit_loss_percent: f64,

    /// Emergency loss percentage used to force an immediate protective exit.
    pub emergency_exit_percent: f64,

    /// Minimum delay before the normal stop-loss logic is allowed to activate.
    pub min_sl_delay: u64,

    /// Controls whether this trade should automatically close after a configured duration.
    pub enable_trade_duration: bool,

    /// Maximum trade duration in seconds when duration-based closing is enabled.
    pub trade_duration_secs: Option<u64>,
}


// ============================================================
// PENDING CLOSE
// ============================================================

/// An exit order currently working against an existing Trade.
///
/// Created BEFORE the REST close request is sent.
///
/// Removed only after:
///
///     ExecEvent::CloseFill
///
/// or a terminal failure.
#[derive(Debug, Clone)]
pub struct PendingClose {
    /// Engine-generated close request ID.
    pub cid: String,

    /// Exchange close order ID.
    ///
    /// None until REST ACK is received.
    pub oid: Option<String>,

    /// Trade being closed.
    pub trade_id: String,

    pub symbol: String,

    /// Quantity requested for close.
    pub requested_qty: Option<f64>,

    /// Cumulative quantity successfully closed.
    pub filled_qty: f64,

    /// Cumulative average EXIT fill price.
    pub avg_fill_px: Option<f64>,

    /// Engine market price that triggered the close request.
    pub signal_price: f64,

    /// Execution IDs already processed.
    pub execution_ids: HashSet<String>,

    /// Time close request was created.
    pub ts_ms: i64,
}


// ============================================================
// PENDING ORDER BOOKS
// ============================================================

pub type PendingOpens =
    HashMap<String, PendingOpen>;

pub type PendingCloses =
    HashMap<String, PendingClose>;